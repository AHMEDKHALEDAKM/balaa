// Douglas-Peucker in degrees: 0.00015 deg is about 15 m in Cairo.
const tolerance = 0.00015;
function simplify(points) {
  if (points.length < 5) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [x1, y1] = points[a];
    const [x2, y2] = points[b];
    const dx = x2 - x1;
    const dy = y2 - y1;
    const length = Math.hypot(dx, dy) || 1e-12;
    let best = -1;
    let far = 0;
    for (let i = a + 1; i < b; i++) {
      const [x, y] = points[i];
      const distance = Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / length;
      if (distance > far) {
        far = distance;
        best = i;
      }
    }
    if (far > tolerance) {
      keep[best] = 1;
      stack.push([a, best], [best, b]);
    }
  }
  const out = points.filter((_, i) => keep[i]);
  return out.length >= 4 ? out : points;
}
const round = ([x, y]) => [Math.round(x * 1e5) / 1e5, Math.round(y * 1e5) / 1e5];

const source = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const districts = source.features
  .filter((f) => /cairo/i.test(f.properties.adm1_name))
  .map((f) => {
    const entry = names[f.properties.adm2_pcode];
    if (!entry) throw new Error(`No name for ${f.properties.adm2_pcode}`);
    const polygons =
      f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    // Each polygon becomes its own entry (outer ring first, then holes) so point-in-polygon
    // stays simple; MultiPolygon districts appear more than once with the same id.
    return polygons.map((rings) => ({
      id: entry[0],
      nameAr: entry[1],
      nameEn: entry[2],
      rings: rings.map((ring) => simplify(ring.map(round))),
    }));
  })
  .flat()
  .sort((a, b) => a.id.localeCompare(b.id));

const list = [...new Map(districts.map((d) => [d.id, [d.id, d.nameAr, d.nameEn]])).values()];
